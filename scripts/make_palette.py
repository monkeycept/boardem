"""Generate src/theme/palette.ts: Tailwind-style colour ramps anchored on colours
from Sanzo Wada's "A Dictionary of Color Combinations" (values from the MIT-licensed
dataset at github.com/mattdesl/dictionary-of-colour-combinations).

The app UI uses combination 155: Deep Indigo, Benzol Green, Jasper Red.

Usage: python3 scripts/make_palette.py
"""
import json
import math
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "theme" / "palette.ts"

# name -> (anchor hex, step the anchor should sit at, chroma multiplier for the neutral ramp)
RAMPS = {
    "ink": ("#051230", 950),  # Deep Indigo (neutral surfaces + text)
    "sea": ("#00978d", 500),  # Benzol Green (primary accent)
    "jasper": ("#eb5324", 500),  # Jasper Red (warm accent, alerts)
    "jade": ("#96d1aa", 300),  # Cobalt Green (online / success)
    "ocher": ("#e2b540", 400),  # Yellow Ocher (demo / warning)
}

STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950]
# Target OKLab lightness per step (roughly Tailwind's ladder).
L_TARGET = {50: 0.975, 100: 0.945, 200: 0.89, 300: 0.82, 400: 0.74, 500: 0.65, 600: 0.56, 700: 0.48, 800: 0.40, 900: 0.32, 950: 0.24}
# The neutral ramp runs darker so ink-950 is the Deep Indigo itself.
INK_L = {50: 0.975, 100: 0.94, 200: 0.88, 300: 0.80, 400: 0.68, 500: 0.56, 600: 0.45, 700: 0.36, 800: 0.29, 900: 0.235, 950: None}


def srgb_to_linear(c):
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def linear_to_srgb(c):
    return 12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055


def hex_to_oklch(h):
    r, g, b = (srgb_to_linear(int(h[i : i + 2], 16) / 255) for i in (1, 3, 5))
    l = 0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b
    m = 0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b
    s = 0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b
    l, m, s = (x ** (1 / 3) for x in (l, m, s))
    L = 0.2104542553 * l + 0.7936177850 * m - 0.0040720468 * s
    a = 1.9779984951 * l - 2.4285922050 * m + 0.4505937099 * s
    bb = 0.0259040371 * l + 0.7827717662 * m - 0.8086757660 * s
    return L, math.hypot(a, bb), math.atan2(bb, a)


def oklch_to_rgb(L, C, H):
    a, b = C * math.cos(H), C * math.sin(H)
    l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s = (L - 0.0894841775 * a - 1.2914855480 * b) ** 3
    r = 4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s
    g = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s
    bl = -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s
    return r, g, bl


def in_gamut(rgb):
    return all(-1e-4 <= c <= 1 + 1e-4 for c in rgb)


def to_hex(L, C, H):
    # Reduce chroma until the colour fits in sRGB.
    while C > 0 and not in_gamut(oklch_to_rgb(L, C, H)):
        C -= 0.002
    r, g, b = (min(1, max(0, linear_to_srgb(max(0, c)))) for c in oklch_to_rgb(L, max(C, 0), H))
    return "#%02x%02x%02x" % (round(r * 255), round(g * 255), round(b * 255))


def ramp(name, anchor, anchor_step):
    L0, C0, H = hex_to_oklch(anchor)
    out = {}
    for step in STEPS:
        if step == anchor_step:
            out[step] = anchor
            continue
        if name == "ink":
            L = INK_L[step]
            # Neutrals: a whisper of the indigo hue, a little more chroma in the darks.
            C = 0.012 + 0.05 * (1 - L) ** 2
        else:
            L = L_TARGET[step]
            # Keep the anchor's chroma in the middle, taper toward white and black.
            taper = 1 - abs(L - L0) ** 1.6 * 1.9
            C = C0 * max(0.12, taper)
        out[step] = to_hex(L, C, H)
    return out


def main():
    ramps = {name: ramp(name, hx, step) for name, (hx, step) in RAMPS.items()}
    body = json.dumps({k: {str(s): v for s, v in r.items()} for k, r in ramps.items()}, indent=2)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by scripts/make_palette.py — edit the anchors there, not here.\n"
        "// Colour ramps anchored on Sanzo Wada's Dictionary of Color Combinations (combination 155).\n"
        f"export const ramps = {body} as const\n"
    )
    for k, r in ramps.items():
        print(k.ljust(7), " ".join(r[s] for s in STEPS))


if __name__ == "__main__":
    main()
